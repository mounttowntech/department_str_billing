const router = require("express").Router();

const c = require("../controllers/NotificationController");

const {
  verifyToken,
} = require("../middleware/authMiddleware");

/*
|--------------------------------------------------------------------------
| CREATE
|--------------------------------------------------------------------------
*/

router.post(
  "/create",
  verifyToken,
  c.createNotification
);

/*
|--------------------------------------------------------------------------
| MY NOTIFICATIONS
|--------------------------------------------------------------------------
*/

router.get(
  "/all",
  verifyToken,
  c.getMyNotifications
);

/*
|--------------------------------------------------------------------------
| GET BY ID
|--------------------------------------------------------------------------
*/

router.get(
  "/:id",
  verifyToken,
  c.getNotificationById
);

/*
|--------------------------------------------------------------------------
| UPDATE
|--------------------------------------------------------------------------
*/

router.put(
  "/update/:id",
  verifyToken,
  c.updateNotification
);

/*
|--------------------------------------------------------------------------
| DELETE
|--------------------------------------------------------------------------
*/

router.delete(
  "/delete/:id",
  verifyToken,
  c.deleteNotification
);

/*
|--------------------------------------------------------------------------
| MARK SINGLE AS READ
|--------------------------------------------------------------------------
*/

router.put(
  "/read/:id",
  verifyToken,
  c.markAsRead
);

/*
|--------------------------------------------------------------------------
| MARK ALL AS READ
|--------------------------------------------------------------------------
*/

router.put(
  "/read-all",
  verifyToken,
  c.markAllAsRead
);

/*
|--------------------------------------------------------------------------
| UNREAD COUNT
|--------------------------------------------------------------------------
*/

router.get(
  "/unread-count",
  verifyToken,
  c.getMyUnreadCount
);

module.exports = router;